import { useEffect, useState } from "react";
import { useNavigate, useLocation } from "react-router-dom";
import { useUser } from "../context/UserContext";
import toast from "react-hot-toast";

function LinkedinLoginPage() {
  const navigate = useNavigate();
  const location = useLocation();
  const { dbUser, refreshUser } = useUser();
  const [loading, setLoading] = useState(false);

  useEffect(() => {
    // Check for user data in URL after redirect from backend
    const urlParams = new URLSearchParams(location.search);
    const userData = urlParams.get("user");

    if (userData) {
      try {
        const user = JSON.parse(decodeURIComponent(userData));
        localStorage.setItem("user", JSON.stringify(user));
        toast.success(`Connected LinkedIn for ${user.firstName || user.name || "account"}!`);
        if (refreshUser) refreshUser();
      } catch (e) {
        console.error("Failed to parse LinkedIn callback data", e);
      }
      navigate("/app/profile");
    }
  }, [location, navigate, refreshUser]);

  const handleLogin = () => {
    setLoading(true);
    const state = dbUser?.id || dbUser?.firebaseUID || "guest";
    // Redirect through backend which handles OAuth credentials securely
    window.location.href = `http://localhost:4000/api/v1/linkedin/login?state=${encodeURIComponent(state)}`;
  };

  return (
    <div style={{ maxWidth: 500, margin: "80px auto", padding: "0 20px" }}>
      <div className="glass-card animate-fadeInUp" style={{ padding: "40px 32px", textAlign: "center" }}>
        <div style={{
          width: 60, height: 60, borderRadius: 16, background: "rgba(10,102,194,0.12)",
          border: "1px solid rgba(10,102,194,0.3)", display: "flex", alignItems: "center",
          justifyContent: "center", margin: "0 auto 20px",
        }}>
          <svg width="28" height="28" viewBox="0 0 24 24" fill="#0a66c2">
            <path d="M19 0h-14c-2.761 0-5 2.239-5 5v14c0 2.761 2.239 5 5 5h14c2.762 0 5-2.239 5-5v-14c0-2.761-2.238-5-5-5zm-11 19h-3v-11h3v11zm-1.5-12.268c-.966 0-1.75-.79-1.75-1.764s.784-1.764 1.75-1.764 1.75.79 1.75 1.764-.783 1.764-1.75 1.764zm13.5 12.268h-3v-5.604c0-3.368-4-3.113-4 0v5.604h-3v-11h3v1.765c1.396-2.586 7-2.777 7 2.476v6.759z"/>
          </svg>
        </div>

        <h1 style={{ fontSize: 24, fontWeight: 800, letterSpacing: "-0.02em", marginBottom: 8 }}>
          LinkedIn Connection
        </h1>
        <p style={{ fontSize: 14, color: "var(--text-secondary)", marginBottom: 28 }}>
          Connect your LinkedIn account to publish viral professional posts generated by your AI agents.
        </p>

        <button
          onClick={handleLogin}
          disabled={loading}
          className="btn btn-primary"
          style={{ width: "100%", justifyContent: "center" }}
        >
          {loading ? "Redirecting to LinkedIn..." : "Sign in with LinkedIn"}
        </button>

        <div style={{ marginTop: 20 }}>
          <button
            onClick={() => navigate("/app/profile")}
            className="btn btn-ghost btn-sm"
          >
            ← Back to Profile
          </button>
        </div>
      </div>
    </div>
  );
}

export default LinkedinLoginPage;

